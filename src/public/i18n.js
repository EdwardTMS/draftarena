  let currentLang = localStorage.getItem('lang') || 'it';

  function t(page, key) {
    const d = dictionaries[page];
    if (!d) return key;
    return (d[currentLang] || d.it)[key] || (d.it[key] || key);
  }

  function applyLang(page) {
    const d = dictionaries[page];
    if (!d) return;
    const T = d[currentLang] || d.it;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.dataset.i18n;
      if (T[key] !== undefined) el.textContent = T[key];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.dataset.i18nHtml;
      if (T[key] !== undefined) el.innerHTML = T[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.dataset.i18nPlaceholder;
      if (T[key] !== undefined) el.placeholder = T[key];
    });
    document.documentElement.lang = currentLang;
    const toggle = document.getElementById('lang-toggle');
    if (toggle) toggle.textContent = currentLang === 'it' ? '🇬🇧 EN' : '🇮🇹 IT';
  }

  function setLang(lang, page) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
    if (page) applyLang(page);
  }

  function toggle(page) {
    setLang(currentLang === 'it' ? 'en' : 'it', page);
  }

  function lang() { return currentLang; }

  return { t, applyLang, setLang, toggle, lang };
